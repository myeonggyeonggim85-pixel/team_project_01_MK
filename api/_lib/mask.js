// AI 로 보내기 전에 계좌번호·전화번호·주민등록번호를 가린다(기획서 Ⅶ-2 개인정보)
export function maskPersonal(text) {
  return String(text || '')
    .replace(/\d{6}\s*-\s*[1-4]\d{6}/g, '[주민등록번호]')
    .replace(/01[016789][-.\s]?\d{3,4}[-.\s]?\d{4}/g, '[연락처]')
    .replace(/0\d{1,2}[-.\s]\d{3,4}[-.\s]\d{4}/g, '[연락처]')
    .replace(/\d{2,6}(?:[-\s]\d{2,7}){2,3}/g, (m) => (/^(19|20)\d{2}[-\s]\d{1,2}[-\s]\d{1,2}$/.test(m) ? m : '[계좌번호]')) // 날짜는 남긴다
    .replace(/\d{10,16}/g, '[계좌번호]');
}
